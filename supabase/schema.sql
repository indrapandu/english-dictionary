-- A single request saves the word and all its examples in one transaction.
-- SECURITY INVOKER preserves the caller's RLS policies.
create or replace function public.save_word(p_word_id bigint, p_word jsonb, p_examples jsonb)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
    saved_id bigint;
    caller_id uuid := auth.uid();
begin
    if caller_id is null then
        raise exception 'Please log in again.' using errcode = '42501';
    end if;
    if jsonb_typeof(p_word) is distinct from 'object'
       or jsonb_typeof(p_examples) is distinct from 'array' then
        raise exception 'Invalid word or examples.' using errcode = '22023';
    end if;

    if p_word_id is null then
        insert into public.words (
            user_id, word, part_of_speech, pronunciation, meaning_en, meaning_id,
            notes, favorite, mastery_level
        ) values (
            caller_id, btrim(p_word->>'word'), nullif(btrim(p_word->>'part_of_speech'), ''),
            nullif(btrim(p_word->>'pronunciation'), ''), btrim(p_word->>'meaning_en'),
            nullif(btrim(p_word->>'meaning_id'), ''), nullif(btrim(p_word->>'notes'), ''),
            coalesce((p_word->>'favorite')::boolean, false), coalesce(p_word->>'mastery_level', 'New')
        ) returning id into saved_id;
    else
        update public.words set
            word = btrim(p_word->>'word'),
            part_of_speech = nullif(btrim(p_word->>'part_of_speech'), ''),
            pronunciation = nullif(btrim(p_word->>'pronunciation'), ''),
            meaning_en = btrim(p_word->>'meaning_en'),
            meaning_id = nullif(btrim(p_word->>'meaning_id'), ''),
            notes = nullif(btrim(p_word->>'notes'), ''),
            favorite = coalesce((p_word->>'favorite')::boolean, false),
            mastery_level = coalesce(p_word->>'mastery_level', 'New')
        where id = p_word_id and user_id = caller_id
        returning id into saved_id;
        if saved_id is null then
            raise exception 'Word not found or access denied.' using errcode = '42501';
        end if;
        delete from public.word_examples where word_id = saved_id;
    end if;

    insert into public.word_examples (word_id, sentence, translation, notes)
    select saved_id, btrim(example->>'sentence'), nullif(btrim(example->>'translation'), ''),
           nullif(btrim(example->>'notes'), '')
    from jsonb_array_elements(p_examples) with ordinality as entry(example, position)
    order by position;

    return saved_id;
end;
$$;

revoke execute on function public.save_word(bigint, jsonb, jsonb) from public, anon;
grant execute on function public.save_word(bigint, jsonb, jsonb) to authenticated;
